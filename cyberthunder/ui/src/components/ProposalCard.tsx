// One decision. Answers the five questions in plain words:
// what is wrong, why it matters, what will change, could it break something, how to undo.
import { Alert, Badge, Button, Card, Checkbox, Divider, Group, Stack, Text, Title, Tooltip } from '@mantine/core';
import { IconArrowBackUp, IconCheck, IconChecklist, IconPlayerPlay, IconX } from '@tabler/icons-react';
import type { ReactNode } from 'react';
import type { ProposalPlus } from '../api/types';
import { fmtAgo, label } from '../lib/format';
import { isSuppressed } from '../lib/findingAssurance';
import { ApplyTimeline } from './ApplyTimeline';
import { CitationChips } from './CitationChips';
import { DiffButton } from './ProposalDiff';
import { RiskTagsForFix } from './FixPanel';
import { AssetIcon, CodeBlock, Collapsible, Mono, SeverityBadge, SimulatedBadge, StateBadge } from './common';

export interface ProposalActions {
  approve: (p: ProposalPlus) => void;
  deny: (p: ProposalPlus) => void;
  apply: (p: ProposalPlus) => void;
  rollback: (p: ProposalPlus) => void;
  /** record that a runbook (manual) change was carried out; the server rescans and sets the state */
  verify?: (p: ProposalPlus) => void;
  openFinding: (findingId: string) => void;
}

const KIND_LABEL: Record<string, string> = {
  script: 'script', powershell: 'PowerShell script', config_snippet: 'config snippet', manifest: 'manifest', runbook: 'runbook (manual steps)',
};

function Q({ n, title, children }: { n: number; title: string; children: ReactNode }) {
  return (
    <Stack gap={4}>
      <Text size="xs" fw={700} c="dimmed" tt="uppercase">{n}. {title}</Text>
      {children}
    </Stack>
  );
}

export function RiskTags({ p }: { p: ProposalPlus }) {
  const fix = p.fix;
  if (!fix) return <Text size="sm" c="dimmed">No library entry found for {p.fix_ref}; treat as unknown risk.</Text>;
  return <RiskTagsForFix fix={fix} />;
}

export function ProposalCard({
  p, actions, busy, selected, onSelect, focused,
}: {
  p: ProposalPlus;
  actions: ProposalActions;
  busy?: boolean;
  selected?: boolean;
  onSelect?: (v: boolean) => void;
  focused?: boolean;
}) {
  const f = p.finding;
  const ex = f?.explanation ?? null;
  const fix = p.fix;
  const citations = Array.from(new Set([...(ex?.citations ?? []), ...p.citations]));
  const ruleIds = [f?.rule_version, f?.rule_id].filter(Boolean) as string[];
  const auto = (p.decided_by ?? '').startsWith('policy:');
  const suppressed = isSuppressed(f?.review);

  return (
    <Card
      withBorder
      radius="md"
      padding="lg"
      id={`proposal-${p.id}`}
      style={focused ? { outline: '2px solid var(--mantine-color-blue-5)', outlineOffset: 2 } : undefined}
    >
      <Stack gap="md">
        <Group justify="space-between" wrap="nowrap" align="flex-start">
          <Group gap="sm" wrap="nowrap" align="flex-start">
            {onSelect && (
              <Checkbox checked={!!selected} onChange={(e) => onSelect(e.currentTarget.checked)} aria-label="Select for bulk action" mt={4} />
            )}
            <SeverityBadge severity={p.severity} size="lg" />
            <Stack gap={2}>
              <Title order={4} style={{ lineHeight: 1.25 }}>{f?.title ?? p.title}</Title>
              <Group gap={6}>
                <AssetIcon type={p.target?.asset_type} size={16} />
                <Text size="sm" fw={600}>{p.target?.name ?? p.host}</Text>
                <SimulatedBadge simulated={p.target?.simulated} />
                {ruleIds.map((r) => <Mono key={r}>{r}</Mono>)}
              </Group>
            </Stack>
          </Group>
          <Stack gap={4} align="flex-end">
            <StateBadge state={p.state} />
            <Text size="xs" c="dimmed">{fmtAgo(p.created_at)}</Text>
          </Stack>
        </Group>

        <Q n={1} title="What is wrong">
          <Text size="sm">{f?.description ? f.description.slice(0, 400) + (f.description.length > 400 ? '...' : '') : p.title}</Text>
        </Q>

        <Q n={2} title="Why it matters">
          <Text size="sm">{ex?.risk ?? p.risk}</Text>
          {ex?.impact && <Text size="sm" fs="italic">{ex.impact}</Text>}
          <CitationChips ids={citations} onOpen={() => actions.openFinding(p.finding_id)} />
          <Text size="xs" c="dimmed">
            {ex ? (ex.fallback || ex.backend === 'template' ? 'Explanation: template (no model)' : `Generated by ${ex.backend}${ex.model ? `/${ex.model}` : ''}`) : 'Explanation: template text from the proposal'}
            {ex && ex.dropped_citations.length > 0 && ` · ${ex.dropped_citations.length} uncited claim(s) dropped by the validator`}
          </Text>
        </Q>

        <Q n={3} title="What will change">
          <Group gap="xs">
            <Text size="sm" fw={600}>{fix?.title ?? p.title}</Text>
            <Badge variant="outline" color="gray" size="sm">{KIND_LABEL[fix?.kind ?? ''] ?? fix?.kind ?? 'unknown kind'}</Badge>
            <Mono>{p.fix_ref}</Mono>
          </Group>
          <Collapsible title="exact change">
            <CodeBlock code={fix?.preview ?? p.fix_preview} />
          </Collapsible>
        </Q>

        <Q n={4} title="Could it break something">
          <RiskTags p={p} />
        </Q>

        <Q n={5} title="How to undo">
          <Text size="sm" style={{ whiteSpace: 'pre-wrap' }}>{fix?.rollback_plan ?? p.rollback_plan}</Text>
        </Q>

        {(auto || p.policy?.auto_eligible) && (
          <Group gap="xs">
            {auto ? (
              <Badge color="cyan" variant="light" tt="none" size="lg">
                standing approval: {p.policy?.rule ?? 'policy'}, signed by {(p.decided_by ?? '').replace(/^policy:/, '')}
              </Badge>
            ) : (
              <Tooltip label={p.policy?.reasons.join('; ') || 'eligible under the standing approval policy'}>
                <Badge color="cyan" variant="outline" tt="none">policy-eligible: {p.policy?.rule}</Badge>
              </Tooltip>
            )}
          </Group>
        )}
        {p.decided_by && (
          <Text size="xs" c="dimmed">
            {label(p.state)} by {p.decided_by} {fmtAgo(p.decided_at)}{p.decision_note ? `: "${p.decision_note}"` : ''}
          </Text>
        )}

        <ApplyTimeline proposal={p} />

        <Divider />
        {suppressed && <Alert color="orange" title="Apply blocked by human review">
          <Text size="sm">{f?.review?.current?.reason || 'An active dismissal applies to the current evidence.'}</Text>
          <Text size="sm">Open Finding detail to review the evidence and recorded decision.</Text>
        </Alert>}
        <Group gap="sm">
          {p.state === 'proposed' && (
            <>
              <Button size="md" color="green" leftSection={<IconCheck size={18} />} loading={busy} onClick={() => actions.approve(p)}>Approve</Button>
              <Button size="md" color="red" variant="light" leftSection={<IconX size={18} />} disabled={busy} onClick={() => actions.deny(p)}>Deny</Button>
            </>
          )}
          {p.state === 'approved' && (
            <Button size="md" color="blue" leftSection={<IconPlayerPlay size={18} />} loading={busy} disabled={suppressed} onClick={() => actions.apply(p)}>Apply</Button>
          )}
          {p.state === 'applying' && <Button size="md" loading variant="light">Applying</Button>}
          {(p.state === 'applied' || p.state === 'verified') && (
            <Button size="md" color="violet" variant="light" leftSection={<IconArrowBackUp size={18} />} loading={busy} onClick={() => actions.rollback(p)}>Rollback</Button>
          )}
          {p.state === 'applied' && fix?.kind === 'runbook' && actions.verify && (
            <Button size="md" color="teal" variant="light" leftSection={<IconChecklist size={18} />} loading={busy} onClick={() => actions.verify?.(p)}>Verify</Button>
          )}
          <DiffButton proposalId={p.id} state={p.state} />
          <Button size="md" variant="subtle" onClick={() => actions.openFinding(p.finding_id)}>Finding detail</Button>
        </Group>
      </Stack>
    </Card>
  );
}
